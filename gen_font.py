#!/usr/bin/env python3
"""Rasterize DejaVu glyphs with PIL and emit font.ts (base64-packed 1-bit bitmaps).

Run once during the build. The generated font.ts is self-contained data
shipped in the repo; the entry program needs no font files at run time.
"""
import base64
import json
from PIL import Image, ImageDraw, ImageFont

BODY_CHARS = (
    "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789"
    " .,!?;:'\"()—-–/&%@#*+=_"
)
TITLE_CHARS = "YOUAREINVTD!,"  # chars of "YOU ARE INVITED!" + comma

BODY_FONT_PATH = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"
TITLE_FONT_PATH = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"


def rasterize(font_path, size, chars):
    font = ImageFont.truetype(font_path, size)
    glyphs = {}
    for ch in chars:
        # advance width
        adv = font.getlength(ch)
        # bounding box of the drawn glyph
        bbox = font.getbbox(ch)  # (x0, y0, x1, y1) relative to anchor top-left
        # draw on a temp image large enough, threshold to 1-bit
        img = Image.new("L", (size * 2, size * 2), 0)
        d = ImageDraw.Draw(img)
        d.text((size, size), ch, font=font, fill=255)
        px = img.load()
        # find tight bbox of ink
        xs = [x for x in range(img.width) for y in range(img.height) if px[x, y] > 127]
        ys = [y for x in range(img.width) for y in range(img.height) if px[x, y] > 127]
        if not xs:
            glyphs[ch] = {"a": round(adv), "w": 0, "h": 0, "x": 0, "y": 0, "d": ""}
            continue
        x0, x1, y0, y1 = min(xs), max(xs), min(ys), max(ys)
        w, h = x1 - x0 + 1, y1 - y0 + 1
        bits = bytearray()
        cur = 0
        nbits = 0
        for y in range(y0, y1 + 1):
            for x in range(x0, x1 + 1):
                cur = (cur << 1) | (1 if px[x, y] > 127 else 0)
                nbits += 1
                if nbits == 8:
                    bits.append(cur)
                    cur = 0
                    nbits = 0
        if nbits:
            bits.append(cur << (8 - nbits))
        # xOffset: ink left edge relative to pen x (pen at size, size anchor)
        # yOffset: ink top edge relative to baseline. Baseline is at size + font.getmetrics()[0]
        ascent, descent = font.getmetrics()
        baseline_y = size + ascent
        glyphs[ch] = {
            "a": round(adv),
            "w": w,
            "h": h,
            "x": x0 - size,
            "y": y0 - baseline_y,
            "d": base64.b64encode(bytes(bits)).decode(),
        }
    return glyphs


def emit(glyphs, name):
    lines = [f"export const {name}: Record<string, Glyph> = {{"]
    for ch, g in glyphs.items():
        lines.append(
            f"  {json.dumps(ch)}: {{ a: {g['a']}, w: {g['w']}, h: {g['h']}, "
            f"x: {g['x']}, y: {g['y']}, d: \"{g['d']}\" }},"
        )
    lines.append("};")
    return "\n".join(lines)


body = rasterize(BODY_FONT_PATH, 30, BODY_CHARS)
title = rasterize(TITLE_FONT_PATH, 76, TITLE_CHARS)

header = """// Font bitmaps rasterized from DejaVu Sans (body, regular 30px) and
// DejaVu Sans Bold (title, 76px) with PIL on the build machine, then
// embedded here as base64-packed 1-bit bitmaps. The entry program is
// fully self-contained: no font files, no network at run time.
// Generated by gen_font.py (run during the build, see session log).
// Each glyph: advance, width, height, xOffset, yOffset (relative to the
// pen position and the baseline), base64-packed bitmap, row-major.
export interface Glyph { a: number; w: number; h: number; x: number; y: number; d: string; }
"""
with open("font.ts", "w") as f:
    f.write(header + emit(body, "BODY_FONT") + "\n" + emit(title, "TITLE_FONT") + "\n")

print("body glyphs:", len(body), "title glyphs:", len(title))
import os
print("font.ts bytes:", os.path.getsize("font.ts"))
# sanity: print a few advances
for ch in "Dear Judge,":
    print(repr(ch), body[ch]["a"], body[ch]["w"], body[ch]["h"])
print("title YOU:", title["Y"], title["O"], title["U"])
